const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
require.extensions['.ts']=(m,file)=>m._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true}}).outputText,file);
const {isGenuineOem,conditionFrom,verifiedOemOffer,listingOriginality}=require('../lib/oem-pricing.ts');
const {parseProductPage,publicAddress}=require('../lib/product-page.ts');
assert.equal(isGenuineOem('OEM reference 4G9807511P'),false);
assert.equal(isGenuineOem('Original aftermarket replacement OEM quality'),false);
assert.equal(isGenuineOem('Genuine original Audi part'),true);
assert.equal(conditionFrom('new or used'),null);
assert.equal(conditionFrom('used damaged'),null);
assert.equal(conditionFrom('https://schema.org/NewCondition'),'new');
const html='<script type="application/ld+json">'+JSON.stringify({'@type':'Product',mpn:'4G9807511P',name:'Genuine original Audi rear bumper',image:'https://example.com/real.jpg',offers:{price:'700',priceCurrency:'EUR',itemCondition:'https://schema.org/NewCondition'}})+'</script>';
const page=parseProductPage(html,'https://example.com/item','4g9807511p');
assert.deepEqual(page.images,['https://example.com/real.jpg']);
assert.equal(parseProductPage(html,'https://example.com/item','4G9807511R'),null);
assert.equal(parseProductPage('<title>All bumpers</title><p>4G9807511P</p><meta property="og:image" content="https://example.com/wrong.jpg">','https://example.com/category','4G9807511P'),null);
assert.equal(verifiedOemOffer({price:700,currency:'EUR',condition:'new'},page),true);
assert.equal(verifiedOemOffer({price:700,currency:'EUR',condition:'used'},page),false);
assert.equal(verifiedOemOffer({price:70,currency:'EUR',condition:'new'},page),false);
assert.equal(verifiedOemOffer({price:700,currency:'EUR',condition:'new'},{...page,title:'Replacement OEM-quality bumper'}),false);
